"""
Generates the film's music bed: an original, quiet ambient pad, so the
film has no licensing questions. Swap it for a licensed track any time by
pointing src/music.json at another file in public/.

    python3 scripts/generate-music.py      (needs numpy)

Shape (matches the story, 108 s):
  0:00–1:01  warm pad only (problem + research) — calm, unhurried
  1:01–1:41  a soft bell motif joins at the Stack Up reveal (product)
  1:41–1:48  resolves to the home chord and fades with the picture
"""
import json
import subprocess
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "public" / "audio"
OUT_DIR.mkdir(parents=True, exist_ok=True)
SR = 44100
LENGTH = 108.0
N = int(SR * LENGTH)
t = np.arange(N) / SR


def hz(midi: float) -> float:
    return 440.0 * 2 ** ((midi - 69) / 12)


# D major, gentle: Dmaj9 · Bm9 · Gmaj9 · A(add9)/C# — 16 chords of 6.75 s
CHORDS = [
    [50, 57, 61, 64, 66],  # Dmaj9
    [47, 54, 57, 61, 62],  # Bm9
    [43, 50, 54, 57, 59],  # Gmaj9
    [49, 52, 57, 59, 64],  # A(add9)/C#
]
CHORD_LEN = LENGTH / 16
XFADE = 1.6

pad = np.zeros((N, 2))
for i in range(16):
    notes = CHORDS[i % 4] if i < 15 else CHORDS[0]  # end on home
    start = i * CHORD_LEN - XFADE / 2
    end = (i + 1) * CHORD_LEN + XFADE / 2
    a, b = max(int(start * SR), 0), min(int(end * SR), N)
    seg = t[a:b]
    rel = (seg - start) / (end - start)
    env = np.clip(np.minimum(rel / (XFADE / (end - start)), (1 - rel) / (XFADE / (end - start))), 0, 1)
    env = 0.5 - 0.5 * np.cos(np.pi * env)  # raised-cosine crossfade
    for j, m in enumerate(notes):
        f = hz(m)
        amp = 0.18 if j == 0 else 0.11
        for ch, cents in ((0, -4), (1, 4)):
            ff = f * 2 ** (cents / 1200)
            tone = np.sin(2 * np.pi * ff * seg) + 0.18 * np.sin(2 * np.pi * 2 * ff * seg)
            pad[a:b, ch] += amp * env * tone
    # soft sub on the root
    pad[a:b, :] += (0.12 * env * np.sin(2 * np.pi * hz(notes[0] - 12) * seg))[:, None]

# slow breathing movement
pad *= (0.85 + 0.15 * np.sin(2 * np.pi * 0.07 * t))[:, None]

# bell motif from the reveal (≈1:01) to the closing (≈1:41)
bells = np.zeros((N, 2))
MOTIF = [74, 78, 81, 78, 76, 78, 73, 76]  # D F# A F# E F# C# E
step = CHORD_LEN / 4
k = 0
time = 61.5
while time < 101.0:
    m = MOTIF[k % len(MOTIF)]
    a = int(time * SR)
    dur = int(2.2 * SR)
    seg = np.arange(min(dur, N - a)) / SR
    env = np.exp(-seg * 2.6) * np.minimum(seg / 0.01, 1)
    tone = np.sin(2 * np.pi * hz(m) * seg) + 0.25 * np.sin(2 * np.pi * hz(m) * 3.01 * seg) * np.exp(-seg * 6)
    pan = 0.35 if k % 2 else -0.35
    bells[a:a + len(seg), 0] += 0.07 * (1 - pan) * env * tone
    bells[a:a + len(seg), 1] += 0.07 * (1 + pan) * env * tone
    time += step * (2 if k % 4 == 3 else 1)
    k += 1
# bells fade in/out over 3 s
bell_env = np.clip((t - 61.5) / 3, 0, 1) * np.clip((101.0 - t) / 3, 0, 1)
mix = pad + bells * bell_env[:, None]

# global fades (the film also fades in Remotion) + normalise to -6 dBFS peak
mix *= np.clip(t / 3, 0, 1)[:, None] * np.clip((LENGTH - t) / 5, 0, 1)[:, None]
mix /= np.max(np.abs(mix)) / 0.5

wav = OUT_DIR / "music-bed.wav"
with wave.open(str(wav), "wb") as w:
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(SR)
    w.writeframes((mix * 32767).astype(np.int16).tobytes())

mp3 = OUT_DIR / "music-bed.mp3"
subprocess.run(["npx", "remotion", "ffmpeg", "-y", "-v", "error", "-i", str(wav), "-b:a", "160k", str(mp3)], cwd=ROOT, check=True)
wav.unlink()
(ROOT / "src" / "music.json").write_text(json.dumps({
    "file": "audio/music-bed.mp3",
    "source": "Original ambient bed generated by scripts/generate-music.py (no third-party audio).",
}, indent=2) + "\n")
print(f"wrote {mp3.relative_to(ROOT)} ({mp3.stat().st_size // 1024} KB)")
